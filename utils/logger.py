def log_info(message):
    # Defines a helper for normal informational logs

    print(f"[INFO] {message}")
    # Prints message with INFO label


def log_warning(message):
    # Defines a helper for warning logs

    print(f"[WARN] {message}")
    # Prints message with WARN label


def log_error(message):
    # Defines a helper for error logs

    print(f"[ERROR] {message}")
    # Prints message with ERROR label